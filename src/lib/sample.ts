  canvas.width = w;
  canvas.height = h;
  const g = canvas.getContext('2d');
  if (!g) throw new Error('画布不可用');
  g.fillStyle = '#FFEFD9';
  g.fillRect(0, 0, w, h);
  g.fillStyle = '#B7E0C2';
  g.beginPath();
  g.ellipse(360, 710, 250, 78, 0, 0, Math.PI * 2);
  g.fill();
  g.fillStyle = '#F4C9A8';
  g.beginPath();
  g.ellipse(360, 640, 110, 18, 0, 0, Math.PI * 2);
  g.fill();
  g.fillStyle = '#F7B7C4';
  g.beginPath();
  g.arc(250, 300, 46, 0, Math.PI * 2);
  g.arc(470, 300, 46, 0, Math.PI * 2);
  g.arc(360, 430, 168, 0, Math.PI * 2);
  g.fill();
  g.fillStyle = '#FFE3C2';
  g.beginPath();
  g.ellipse(360, 490, 86, 72, 0, 0, Math.PI * 2);
  g.fill();
  g.fillStyle = '#5C4033';
